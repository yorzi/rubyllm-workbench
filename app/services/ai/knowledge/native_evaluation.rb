require "digest"

module Ai
  module Knowledge
    class NativeEvaluation
      OPERATION = "native_evaluation".freeze
      KINDS = %w[assertions reviewer judge].freeze
      VERSION = 1

      def self.enqueue(answer_run:, case_key:, evaluator_kind: "assertions", model_reference: nil, requested_by: "local_user")
        raise ArgumentError, "Choose assertions, reviewer or judge." unless KINDS.include?(evaluator_kind)

        snapshot = capture(answer_run:, case_key:, evaluator_kind:, model_reference:)
        target = snapshot.fetch("evaluator")["target"] || answer_run.input_snapshot.fetch("target")
        run = nil
        answer_run.transaction do
          chat = answer_run.project.chats.create!(title: "Saved answer evaluation · #{case_key}",
            provider: target.fetch("provider"), model_id: target.fetch("model_id"))
          run = chat.runs.create!(project: answer_run.project, operation: OPERATION, status: :queued, requested_by:,
            input_snapshot_json: { "native_evaluation" => snapshot, "native_evaluation_sha256" => snapshot_checksum(snapshot), "target" => target },
            app_version: ENV.fetch("APP_VERSION", "local"), ruby_llm_version: Gem.loaded_specs.fetch("ruby_llm").version.to_s)
          if evaluator_kind != "assertions"
            run.attempts.create!(sequence: 1, provider: target.fetch("provider"), model_id: target.fetch("model_id"), status: :queued)
          end
        end
        enqueue_job(run)
        run
      end

      def self.capture(answer_run:, case_key:, evaluator_kind:, model_reference:)
        answer_run.reload
        unless answer_run.operation == GroundedAnswer::OPERATION && answer_run.succeeded?
          raise ArgumentError, "Select a successful saved source answer. No answer will be generated by evaluation."
        end
        manifest = Workbench::KnowledgeCaseStudy.manifest
        case_data = Workbench::KnowledgeCaseStudy.cases.find { |entry| entry.fetch("key") == case_key.to_s }
        raise ArgumentError, "Choose a versioned source case." unless case_data

        answer_snapshot = answer_run.input_snapshot.fetch("grounded_answer")
        unless answer_snapshot.fetch("question") == case_data.fetch("question")
          raise ArgumentError, "The answer question must exactly match the selected case question."
        end
        ownership = answer_run.project.settings_json.to_h[Workbench::KnowledgeCaseStudy::OWNERSHIP_KEY]
        revision = ownership&.dig("revisions", manifest.fetch("revision").to_s)
        unless ownership&.fetch("id", nil) == manifest.fetch("id") &&
            revision&.fetch("collection_id", nil) == answer_snapshot.fetch("collection_id") &&
            revision&.fetch("cases_sha256", nil) == manifest.fetch("cases_sha256")
          raise ArgumentError, "The answer must belong to the current imported case-study release."
        end
        artifact = answer_run.artifacts.find_by(id: answer_run.result_summary["artifact_id"], kind: "json", name: "grounded_answer")
        raise ArgumentError, "The saved answer Artifact is missing." unless artifact

        output = artifact.content_json
        GroundedResponse.parse!(JSON.generate(output), snapshot: answer_snapshot)
        {
          "version" => VERSION, "answer_run_id" => answer_run.id, "answer_artifact_id" => artifact.id,
          "answer_snapshot" => answer_snapshot.deep_dup, "answer_output" => output.deep_dup,
          "answer_sha256" => checksum(answer_snapshot, output), "case" => case_data,
          "release" => { "id" => manifest.fetch("id"), "revision" => manifest.fetch("revision"),
            "cases_sha256" => manifest.fetch("cases_sha256"), "corpus_sha256" => revision.fetch("corpus_sha256") },
          "evaluator" => { "kind" => evaluator_kind, "target" => target_for(evaluator_kind, model_reference),
            "max_output_tokens" => 2_048, "max_retries" => 0 },
          "accounting" => { "answer_cost_included" => false, "task_replayed" => false,
            "report_is_usage_mirror" => true, "meaning" => "Configured checks and model judgments are not proof of answer truth." }
        }
      end

      def self.checksum(snapshot, output)
        Digest::SHA256.hexdigest(JSON.generate([ snapshot, output ]))
      end

      def self.snapshot_checksum(snapshot)
        Digest::SHA256.hexdigest(JSON.generate(snapshot))
      end

      def self.target_for(kind, model_reference)
        return nil if kind == "assertions"

        provider, model_id = model_reference.to_s.split("|", 2)
        entries = if kind == "judge"
          Ai::JudgmentCatalog.entries(configured: "true")
        else
          Ai::ModelCatalog.new.entries(capability: "structured_output", configured: "true")
        end
        entry = entries.find { |candidate| candidate.provider == provider && candidate.id == model_id && candidate.interactive? }
        unless entry
          message = kind == "judge" ? "Choose a configured typed judgment model. OpenRouter chat models do not implement RubyLLM::Judge." : "Choose a configured structured-output reviewer model."
          raise ArgumentError, message
        end
        { "provider" => provider, "model_id" => model_id }
      end

      def self.enqueue_job(run)
        Ai::EvaluationJobEnqueuer.call(NativeEvaluationJob, run.id)
      rescue StandardError => error
        run.fail_queued_execution!(operation: OPERATION, error:) do
          run.attempts.first&.finish!(status: :failed, error_class: error.class.name,
            error_code: Ai::ErrorClassifier.code(error), error_message: Ai::ErrorText.safe(error.message))
        end
        raise ArgumentError, "Evaluation could not be queued: #{Ai::ErrorText.safe(error.message)}"
      end
      private_class_method :capture, :target_for, :enqueue_job
    end
  end
end
